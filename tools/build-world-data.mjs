// Builds src/world-data.js: every large/medium airport with scheduled flights.
// Sources: OurAirports (public domain) for airports; mwgg/Airports (MIT) for time zones.
// Usage (developer only): node tools/build-world-data.mjs <ourairports airports.csv> <mwgg airports.json>
import { readFileSync, writeFileSync } from 'node:fs';

function parseCsv(text) {
  const rows = [];
  let row = [], cur = '', q = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { cur += '"'; i += 1; } else if (ch === '"') q = false; else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cur); cur = ''; }
    else if (ch === '\n') { row.push(cur); rows.push(row); row = []; cur = ''; }
    else if (ch !== '\r') cur += ch;
  }
  if (cur || row.length) { row.push(cur); rows.push(row); }
  return rows;
}

const [head, ...rows] = parseCsv(readFileSync(process.argv[2], 'utf8'));
const col = Object.fromEntries(head.map((h, i) => [h, i]));
const tzByIata = {};
for (const a of Object.values(JSON.parse(readFileSync(process.argv[3], 'utf8')))) if (a.iata && a.tz) tzByIata[a.iata] = a.tz;

// Time zone fallback: nearest airport in the same country that has one.
const known = [];
for (const r of rows) {
  const iata = r[col.iata_code];
  if (tzByIata[iata]) known.push([r[col.iso_country], +r[col.latitude_deg], +r[col.longitude_deg], tzByIata[iata]]);
}
function nearestTz(cc, lat, lon) {
  let best = null;
  for (const k of known) {
    if (k[0] !== cc) continue;
    const d = (k[1] - lat) ** 2 + (k[2] - lon) ** 2;
    if (!best || d < best[0]) best = [d, k[3]];
  }
  return best ? best[1] : null;
}

const out = [];
for (const r of rows) {
  const type = r[col.type];
  const iata = r[col.iata_code];
  if (!['large_airport', 'medium_airport'].includes(type) || r[col.scheduled_service] !== 'yes' || !/^[A-Z]{3}$/.test(iata || '')) continue;
  const tz = tzByIata[iata] || nearestTz(r[col.iso_country], +r[col.latitude_deg], +r[col.longitude_deg]);
  const city = (r[col.municipality] || r[col.name] || '').split(/[,(/]/)[0].trim();
  if (!tz || !city) continue;
  // old/other IATA codes listed in keywords (e.g. Bishkek: BSZ now, FRU on most flight sites)
  const alts = (r[col.keywords] || '').split(',').map((k) => k.trim()).filter((k) => /^[A-Z]{3}$/.test(k) && k !== iata);
  out.push([iata, city, r[col.iso_country], +(+r[col.latitude_deg]).toFixed(2), +(+r[col.longitude_deg]).toFixed(2), tz, type === 'large_airport' ? 1 : 0, ...(alts.length ? [alts.join(' ')] : [])]);
}
out.sort((a, b) => b[6] - a[6] || a[0].localeCompare(b[0]));
const js = `// Generated by tools/build-world-data.mjs. Do not edit by hand.
// Airports with scheduled flights. Sources: OurAirports (public domain), mwgg/Airports (MIT, time zones).
// Each row: [IATA, city, country, lat, lon, IANA time zone, large(1)/medium(0), optional 'OLD CODES']
export const WORLD = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/world-data.js', import.meta.url), js);
console.log('airports', out.length, 'large', out.filter((x) => x[6]).length, 'bytes', js.length);
