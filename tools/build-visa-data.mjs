// Builds src/visa-data.js from the open passport-index dataset (MIT licence,
// github.com/ilyankou/passport-index-dataset, last updated 12 Jan 2025).
// Usage (developer only): node tools/build-visa-data.mjs <path to passport-index-tidy-iso2.csv>
import { readFileSync, writeFileSync } from 'node:fs';
import { PLACES } from '../src/places.js';

const csv = readFileSync(process.argv[2], 'utf8').trim().split('\n').slice(1);
const DEST = [...new Set(PLACES.map((p) => p.cc))].sort();
const code = (req) => {
  if (req === '-1') return 'H';                 // own country
  if (/^\d+$/.test(req) || req === 'visa free') return 'F';
  if (req === 'visa on arrival') return 'A';
  if (req === 'eta') return 'T';
  if (req === 'e-visa') return 'E';
  if (req === 'visa required') return 'V';
  if (req === 'no admission' || req === 'covid ban') return 'N';
  return '?';
};
const rows = {};
for (const line of csv) {
  const [p, d, req] = line.split(',');
  if (!DEST.includes(d)) continue;
  rows[p] ??= Object.fromEntries(DEST.map((x) => [x, '?']));
  rows[p][d] = code(req.trim());
}
const table = Object.fromEntries(Object.entries(rows).sort().map(([p, m]) => [p, DEST.map((d) => m[d]).join('')]));
const out = `// Generated by tools/build-visa-data.mjs. Do not edit by hand.
// Source: passport-index-dataset (MIT), data as of 12 January 2025. Always confirm on official sites.
// One letter per destination in VISA_DEST order:
// F visa-free · A visa on arrival · T electronic travel authorisation · E e-visa · V embassy visa · N no admission · H own country · ? unknown
export const VISA_AS_OF = '12 Jan 2025';
export const VISA_DEST = ${JSON.stringify(DEST)};
export const VISA_TABLE = ${JSON.stringify(table)};
`;
writeFileSync(new URL('../src/visa-data.js', import.meta.url), out);
console.log('passports', Object.keys(table).length, 'destinations', DEST.length, 'bytes', out.length);
